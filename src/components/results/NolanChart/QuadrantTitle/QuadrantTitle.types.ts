// The two looks a title of a quadrant has: a tint for a moderate position,
// the full colour for an extreme one.
export type TitleLook = "moderate" | "extreme";

// How its text is written: in the colour of the quadrant (or white on it), in
// the primary colour, or in the neutral grey of a quadrant with no colour.
export type TitleTone = "colored" | "light" | "neutral";
